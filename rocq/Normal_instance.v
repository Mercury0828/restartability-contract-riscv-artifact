(* Normal_instance.v — RESTART-V: the trap-free candidate is generated by ONE execution of the store.

   The candidate E_N of the Stage-2 chain keeps the surviving lane writes of BOTH attempts of the
   faulting vector store: the early writes of the first attempt and the writes of the replay. They
   inherit the faulting run's program order, so an early write is program-ordered before a replay
   write, and their dependencies are those of two dynamic instances. One fault-free execution of a
   unit-stride store generates instead, from the registers of R0,

     (g_one)       exactly one write per element;
     (g_write)     each element write is a memory write ...
     (g_foot)      ... whose footprint is the element's address range ...
     (g_val)       ... and whose bytes carry the element's register value;
     (g_unordered) no program order among the element writes ("element operations are unordered
                   within the instruction");
     (g_position)  one program-order position for all of them: an event of another instruction is
                   program-ordered before (after) one element write iff before (after) every one;
     (g_deps)      common register dependencies: an event of another instruction is an address,
                   data or control source of one element write iff of every one.

   This file defines that predicate (`GenStore`) and the execution G that differs from E_N only in
   program order: G drops the program-order pairs between two element writes (`po_G`), and every
   relation derived from program order (po-loc, fences, preserved program order) is recomputed from
   `po_G`. It proves

     * `generated`: G's memory kernel satisfies `GenStore` with `po_G`, from four facts about the
       faulting run: program order is per hart and total on a hart; the element writes are on one
       hart; between two element writes in program order lie only element writes, trap-region
       events and PMP checks (`Hwindow`); and the two attempts read their address, data and control
       sources from the same producers (`Hdeps`, which alpha guarantees, as the handler writes none
       of the source registers);
     * `G_perbyte_acyclic`, `G_mainmodel_acyclic`: G passes the per-byte check at every byte and the
       main-model check. Every edge of G is an edge of E_N, so this follows from
       `Perbyte.ML_stage2_endtoend_pb`. G has E_N's reads-from, coherence and values, hence the same
       observation.

   0 Admitted / 0 axioms (Print Assumptions normal_instance). Modifies no existing .v file.
   Coq 8.15. *)

