(* monotonicity of the two generic checks in their program-order-derived argument *)
Lemma CnC_poloc_mono : forall Ev B gmoR (P P' : Ev -> Ev -> Prop) isr isw tch rfwR C,
    (forall x y, P' x y -> P x y) ->
    forall x y, CnC Ev B gmoR P' isr isw tch rfwR C x y -> CnC Ev B gmoR P isr isw tch rfwR C x y.
Proof.
  intros Ev B gmoR P P' isr isw tch rfwR C HP x y H.
  destruct H as [H | [H | [H | [Hp [Cx Cy]]]]].
  - left; exact H.
  - right; left; exact H.
  - right; right; left; exact H.
  - right; right; right. split; [exact (HP x y Hp) | split; assumption].
Qed.

Lemma RnC_ppo_mono : forall Ev B Hr gmoR isr isw tch hrt rfwR (P P' : Ev -> Ev -> Prop) C,
    (forall x y, P' x y -> P x y) ->
    forall x y, RnC Ev B Hr gmoR isr isw tch hrt rfwR P' C x y ->
                RnC Ev B Hr gmoR isr isw tch hrt rfwR P C x y.
Proof.
  intros Ev B Hr gmoR isr isw tch hrt rfwR P P' C HP x y H.
  destruct H as [H | [H | [H | [Cx [Cy Hp]]]]].
  - left; exact H.
  - right; left; exact H.
  - right; right; left; exact H.
  - right; right; right. split; [exact Cx | split; [exact Cy | exact (HP x y Hp)]].
Qed.

Section NormalInstance.

  Variable Event : Type.
  Variable eq_ev_dec : forall x y : Event, {x = y} + {x <> y}.
  Variable Byte Hart Value Lane : Type.
  Variable gmo : Event -> Event -> Prop.
  Variable is_write is_read is_load is_store : Event -> Prop.
  Variable touches : Event -> Byte -> Prop.
  Variable wval : Event -> Byte -> Value.
  Variable same_addr addr data ctrl fence : Event -> Event -> Prop.
  Variable hart : Event -> Hart.
  Variable E0 : list Event.
  Variable rf : Event -> Byte -> Event -> Prop.
  Variable po poloc : Event -> Event -> Prop.
  Variable LS : list (Event * Event).
  Variable Ctx : Event -> Prop.
  Variable ctx_dec : forall e, {Ctx e} + {~ Ctx e}.
  Variable is_chk : Event -> Prop.
  Variable chk_dec : forall e, {is_chk e} + {~ is_chk e}.
  Variable lane : Event -> Lane.
  Variable is_lane_write : Event -> Prop.     (* the element writes of the faulting store *)
  Variable lanes : list Lane.
  Variable vdata : Lane -> Byte -> Value.     (* the element values of the data register in R0 *)
  Variable dst : nat.
  Variable lane_index : Lane -> nat.
  Variable byte_addr : Byte -> nat.

  (* ---- the premises of the per-byte Stage-2 theorem ---- *)
  Hypothesis Htot : forall a b, In a E0 -> In b E0 -> a <> b -> gmo a b \/ gmo b a.
  Hypothesis Hrf_touches : forall w b r, rf w b r -> touches w b.
  Hypothesis Hrf_functional : forall w1 w2 x r, rf w1 x r -> rf w2 x r -> w1 = w2.
  Hypothesis Hlanes : forall k d, In (k, d) LS ->
    ML_T1.LaneOK Event Byte Hart Value gmo is_write is_read touches wval addr data hart E0 rf po k d.
  Hypothesis Hkeeper_survives : forall k d, In (k, d) LS -> ~ ML_base.isdel Event LS k.
  Hypothesis Hfault_pb :
    forall b x, ~ clos_trans Event (CfB Event Byte gmo is_write is_read touches E0 rf poloc b) x x.
  Hypothesis Hfault_main :
    forall x, ~ clos_trans Event
      (Frozen_mainmodel.FRf Event Byte Hart gmo is_write is_read is_load is_store touches
         same_addr addr data ctrl fence hart E0 rf po) x x.
  Hypothesis Hrf_src_write : forall w b r, rf w b r -> is_write w.
  Hypothesis Hrf_tgt_read : forall w b r, rf w b r -> is_read r.
  Hypothesis Hctx_silent :
    forall e, Ctx e -> (~ is_read e) /\ (~ is_write e) /\ (forall b, ~ touches e b).
  Hypothesis Hchk_nonmem :
    forall e, is_chk e -> (~ is_read e) /\ (~ is_write e) /\ (forall b, ~ touches e b).

  Definition E_K := Perbyte.E_K Event eq_ev_dec E0 LS Ctx ctx_dec.
  Definition E_MK := Perbyte.E_MK Event eq_ev_dec E0 LS Ctx ctx_dec is_chk chk_dec.

  (* ---- the shape of the faulting run that the generation needs ---- *)
  Hypothesis Hrw : forall e, is_read e -> is_write e -> False.
  Hypothesis Hlane_write_is_write : forall e, is_lane_write e -> is_write e.
  Hypothesis Hkernel_one_write_per_lane :
    forall l, In l lanes ->
      exists w, In w E_K /\ is_lane_write w /\ lane w = l /\
                (forall w', In w' E_K -> is_lane_write w' -> lane w' = l -> w' = w).
  Hypothesis Hlane_write_footprint : forall e l b,
    In e E_K -> is_lane_write e -> lane e = l ->
    (touches e b <->
       Frozen_pmp.lane_lo dst (lane_index l) <= byte_addr b /\
       byte_addr b < Frozen_pmp.lane_hi dst (lane_index l)).
  (* the element writes carry the data register's values (alpha leaves the register unchanged) *)
  Hypothesis Hvalue : forall e b, In e E_K -> is_lane_write e -> touches e b ->
    wval e b = vdata (lane e) b.
  (* program order is per hart and total on a hart; the element writes are on one hart *)
  Hypothesis Hpo_hart : forall a b, po a b -> hart a = hart b.
  Hypothesis Hpo_total : forall a b, In a E0 -> In b E0 -> hart a = hart b -> a <> b ->
    po a b \/ po b a.
  Hypothesis Hinst_hart : forall a b, is_lane_write a -> is_lane_write b -> hart a = hart b.
  (* between two element writes in program order lie only element writes, the trap region and the
     PMP checks *)
  Hypothesis Hwindow : forall a x b, In x E0 -> is_lane_write a -> is_lane_write b ->
    po a x -> po x b -> is_lane_write x \/ Ctx x \/ is_chk x.
  (* both attempts take their address, data and control sources from the same producers *)
  Hypothesis Hdeps : forall x a b, In x E_MK -> ~ is_lane_write x ->
    is_lane_write a -> is_lane_write b ->
    (addr x a <-> addr x b) /\ (data x a <-> data x b) /\ (ctrl x a <-> ctrl x b).

  (* ================================================================================================
     the generation predicate
     ================================================================================================ *)

  Record GenStore (C : list Event) (poR addrR dataR ctrlR : Event -> Event -> Prop) : Prop := {
    g_one : forall l, In l lanes ->
      exists w, In w C /\ is_lane_write w /\ lane w = l /\
                (forall w', In w' C -> is_lane_write w' -> lane w' = l -> w' = w);
    g_write : forall w, In w C -> is_lane_write w -> is_write w;
    g_foot : forall w b, In w C -> is_lane_write w ->
      (touches w b <->
         Frozen_pmp.lane_lo dst (lane_index (lane w)) <= byte_addr b /\
         byte_addr b < Frozen_pmp.lane_hi dst (lane_index (lane w)));
    g_val : forall w b, In w C -> is_lane_write w -> touches w b -> wval w b = vdata (lane w) b;
    g_unordered : forall w w', is_lane_write w -> is_lane_write w' -> ~ poR w w';
    g_position : forall x w w', In x C -> In w C -> In w' C -> ~ is_lane_write x ->
      is_lane_write w -> is_lane_write w' ->
      (poR x w <-> poR x w') /\ (poR w x <-> poR w' x);
    g_deps : forall x w w', In x C -> ~ is_lane_write x -> is_lane_write w -> is_lane_write w' ->
      (addrR x w <-> addrR x w') /\ (dataR x w <-> dataR x w') /\ (ctrlR x w <-> ctrlR x w')
  }.

  (* G's program order, and the relations derived from it *)
  Definition po_G (a b : Event) : Prop := po a b /\ ~ (is_lane_write a /\ is_lane_write b).
  Definition poloc_G (a b : Event) : Prop := poloc a b /\ ~ (is_lane_write a /\ is_lane_write b).
  Definition fence_G (a b : Event) : Prop := fence a b /\ ~ (is_lane_write a /\ is_lane_write b).

  Lemma E_MK_sub_E_K : forall e, In e E_MK -> In e E_K.
  Proof. exact (Stage2_normal_candidate.mem_kernel_sub Event E_K is_chk chk_dec). Qed.

  Lemma E_K_sub_E0 : forall e, In e E_K -> In e E0.
  Proof.
    intros e H. apply (ML_stage2.E_C_sub_E0 Event eq_ev_dec E0 LS).
    exact (ML_stage2.E_K_sub_E_C Event eq_ev_dec E0 LS Ctx ctx_dec e H).
  Qed.

  Lemma E_MK_not_chk : forall e, In e E_MK -> ~ is_chk e.
  Proof.
    intros e H. exact (proj2 (proj1 (Stage2_normal_candidate.In_mem_kernel_iff Event E_K is_chk
                                       chk_dec e) H)).
  Qed.

  Lemma lane_write_in_E_MK : forall e, In e E_K -> is_lane_write e -> In e E_MK.
  Proof.
    intros e H Hl. apply (proj2 (Stage2_normal_candidate.In_mem_kernel_iff Event E_K is_chk chk_dec e)).
    split; [exact H |]. intro Hc. exact (proj1 (proj2 (Hchk_nonmem e Hc)) (Hlane_write_is_write e Hl)).
  Qed.

  (* an event of another instruction that is program-ordered before one element write is before
     every one *)
  Lemma position_before : forall x w w', In x E_MK -> In w' E_MK -> ~ is_lane_write x ->
      is_lane_write w -> is_lane_write w' -> po x w -> po x w'.
  Proof.
    intros x w w' Hx Hw' Nx Lw Lw' P.
    assert (Ix : In x E0) by exact (E_K_sub_E0 x (E_MK_sub_E_K x Hx)).
    assert (Iw' : In w' E0) by exact (E_K_sub_E0 w' (E_MK_sub_E_K w' Hw')).
    assert (Hh : hart x = hart w') by (rewrite (Hpo_hart x w P); exact (Hinst_hart w w' Lw Lw')).
    assert (Hne : x <> w') by (intro E; subst; exact (Nx Lw')).
    destruct (Hpo_total x w' Ix Iw' Hh Hne) as [H | H]; [exact H |].
    exfalso. destruct (Hwindow w' x w Ix Lw' Lw H P) as [L | [C | K]].
    - exact (Nx L).
    - exact (ML_stage2.E_K_trap_free Event eq_ev_dec E0 LS Ctx ctx_dec x (E_MK_sub_E_K x Hx) C).
    - exact (E_MK_not_chk x Hx K).
  Qed.

  Lemma position_after : forall x w w', In x E_MK -> In w' E_MK -> ~ is_lane_write x ->
      is_lane_write w -> is_lane_write w' -> po w x -> po w' x.
  Proof.
    intros x w w' Hx Hw' Nx Lw Lw' P.
    assert (Ix : In x E0) by exact (E_K_sub_E0 x (E_MK_sub_E_K x Hx)).
    assert (Iw' : In w' E0) by exact (E_K_sub_E0 w' (E_MK_sub_E_K w' Hw')).
    assert (Hh : hart w' = hart x)
      by (rewrite <- (Hpo_hart w x P); exact (Hinst_hart w' w Lw' Lw)).
    assert (Hne : w' <> x) by (intro E; subst; exact (Nx Lw')).
    destruct (Hpo_total w' x Iw' Ix Hh Hne) as [H | H]; [exact H |].
    exfalso. destruct (Hwindow w x w' Ix Lw Lw' P H) as [L | [C | K]].
    - exact (Nx L).
    - exact (ML_stage2.E_K_trap_free Event eq_ev_dec E0 LS Ctx ctx_dec x (E_MK_sub_E_K x Hx) C).
    - exact (E_MK_not_chk x Hx K).
  Qed.

  (* The generation predicate needs program order only through the POSITION of the other events: an
     event of another instruction that is program-ordered before (after) one element write is before
     (after) every one. `generated_pos` takes exactly this, and nothing about totality of program
     order, so it covers input graphs in which the element writes of one attempt are unordered. *)
  Definition Position_before : Prop := forall x w w', In x E_MK -> In w' E_MK -> ~ is_lane_write x ->
      is_lane_write w -> is_lane_write w' -> po x w -> po x w'.
  Definition Position_after : Prop := forall x w w', In x E_MK -> In w' E_MK -> ~ is_lane_write x ->
      is_lane_write w -> is_lane_write w' -> po w x -> po w' x.

  Theorem generated_pos : Position_before -> Position_after -> GenStore E_MK po_G addr data ctrl.
  Proof.
    intros position_before position_after.
    constructor.
    - intros l Hl. destruct (Hkernel_one_write_per_lane l Hl) as [w [Hw [Lw [El U]]]].
      exists w. split; [exact (lane_write_in_E_MK w Hw Lw) |].
      split; [exact Lw |]. split; [exact El |].
      intros w' Hw' Lw' El'. exact (U w' (E_MK_sub_E_K w' Hw') Lw' El').
    - intros w _ Lw. exact (Hlane_write_is_write w Lw).
    - intros w b Hw Lw. exact (Hlane_write_footprint w (lane w) b (E_MK_sub_E_K w Hw) Lw eq_refl).
    - intros w b Hw Lw Tw. exact (Hvalue w b (E_MK_sub_E_K w Hw) Lw Tw).
    - intros w w' Lw Lw' [_ N]. exact (N (conj Lw Lw')).
    - intros x w w' Hx Hw Hw' Nx Lw Lw'. split; split.
      + intros [P _]. split; [exact (position_before x w w' Hx Hw' Nx Lw Lw' P) |].
        intros [L _]; exact (Nx L).
      + intros [P _]. split; [exact (position_before x w' w Hx Hw Nx Lw' Lw P) |].
        intros [L _]; exact (Nx L).
      + intros [P _]. split; [exact (position_after x w w' Hx Hw' Nx Lw Lw' P) |].
        intros [_ L]; exact (Nx L).
      + intros [P _]. split; [exact (position_after x w' w Hx Hw Nx Lw' Lw P) |].
        intros [_ L]; exact (Nx L).
    - intros x w w' Hx Nx Lw Lw'. exact (Hdeps x w w' Hx Nx Lw Lw').
  Qed.

  (* the four facts about the faulting run imply the position premises *)
  Theorem generated : GenStore E_MK po_G addr data ctrl.
  Proof. exact (generated_pos position_before position_after). Qed.

  (* ================================================================================================
     G passes both checks
     ================================================================================================ *)

  Definition ppow_G : Event -> Event -> Prop :=
    ML_T1.ppo_wit_L Event Byte is_write is_read is_load is_store touches same_addr addr data ctrl
      fence_G E0 rf po_G LS.
  Definition ppow_E : Event -> Event -> Prop :=
    ML_T1.ppo_wit_L Event Byte is_write is_read is_load is_store touches same_addr addr data ctrl
      fence E0 rf po LS.

  Lemma po_G_of_read : forall a w, is_read a -> po a w -> po_G a w.
  Proof.
    intros a w Ra P. split; [exact P |]. intros [La _]. exact (Hrw a Ra (Hlane_write_is_write a La)).
  Qed.

  Lemma po_G_to_read : forall w b, is_read b -> po w b -> po_G w b.
  Proof.
    intros w b Rb P. split; [exact P |]. intros [_ Lb]. exact (Hrw b Rb (Hlane_write_is_write b Lb)).
  Qed.

  (* every preserved-program-order edge of G is one of E_N *)
  Lemma ppow_G_sub : forall a b, ppow_G a b -> ppow_E a b.
  Proof.
    intros a b H. destruct H.
    - apply ML_T1.pl1; try assumption. exact (proj1 H1).
    - apply ML_T1.pl4; try assumption. exact (proj1 H1).
    - apply ML_T1.pl9; assumption.
    - apply ML_T1.pl10; assumption.
    - apply ML_T1.pl11; assumption.
    - apply ML_T1.pl13; try assumption.
      destruct H2 as [m [Sm [[P1 _] [[P2 _] Hm]]]]. exists m. auto.
    - apply ML_T1.pl12; try assumption.
      destruct H2 as [m [bb [[P1 _] [[P2 _] Hm]]]]. exists m, bb. auto.
    - apply (ML_T1.pl2 _ _ _ _ _ _ _ _ _ _ _ _ _ _ _ _ x).
      destruct H as [[Ra [Rb [Ta [Tb [[Pab _] [Sa [Sb Hnb]]]]]]] Hn].
      split; [| exact Hn].
      split; [exact Ra |]. split; [exact Rb |]. split; [exact Ta |]. split; [exact Tb |].
      split; [exact Pab |]. split; [exact Sa |]. split; [exact Sb |].
      intros [w [Sw [Ww [Tw [Paw Pwb]]]]]. apply Hnb.
      exists w. split; [exact Sw |]. split; [exact Ww |]. split; [exact Tw |].
      split; [exact (po_G_of_read a w Ra Paw) | exact (po_G_to_read w b Rb Pwb)].
  Qed.

  Definition Cn_G_at (b : Byte) :=
    Perbyte.Cn_N_at Event eq_ev_dec Byte Lane gmo is_write is_read touches E0 rf poloc_G LS Ctx
      ctx_dec is_chk chk_dec lanes b.
  Definition Rn_G :=
    RnC (Stage2_normal_candidate.NEv Event Lane) Byte (option Hart)
      (Stage2_normal_candidate.gmo_N Event Lane gmo)
      (Stage2_normal_candidate.is_read_N Event Lane is_read)
      (Stage2_normal_candidate.is_write_N Event Lane is_write)
      (Stage2_normal_candidate.touches_N Event Byte Lane touches)
      (hart_N Event Hart Lane hart)
      (Stage2_normal_candidate.rf_N Event Byte Lane (Perbyte.rf_C Event Byte rf LS))
      (ppo_N Event Lane ppow_G)
      (fun z => In z (Perbyte.E_N Event eq_ev_dec Lane E0 LS Ctx ctx_dec is_chk chk_dec lanes)).

  Theorem G_perbyte_acyclic :
    forall b n, ~ clos_trans (Stage2_normal_candidate.NEv Event Lane) (Cn_G_at b) n n.
  Proof.
    intro b.
    apply (acyclic_sub _ (Perbyte.Cn_N_at Event eq_ev_dec Byte Lane gmo is_write is_read touches E0 rf
                            poloc LS Ctx ctx_dec is_chk chk_dec lanes b)).
    - intros x y H. unfold Cn_G_at, Perbyte.Cn_N_at in *.
      revert H. apply CnC_poloc_mono.
      intros m n Hmn. destruct m as [a | l]; destruct n as [c | l']; simpl in *; try contradiction.
      destruct Hmn as [[Hp _] T]. split; [exact Hp | exact T].
    - exact (Perbyte.Cn_N_at_acyclic Event eq_ev_dec Byte Hart Value Lane gmo is_write is_read touches
               wval addr data hart E0 rf po poloc LS Ctx ctx_dec is_chk chk_dec lanes Htot Hrf_touches
               Hlanes Hfault_pb Hrf_src_write Hrf_tgt_read Hctx_silent Hchk_nonmem b).
  Qed.

  Theorem G_mainmodel_acyclic :
    forall n, ~ clos_trans (Stage2_normal_candidate.NEv Event Lane) Rn_G n n.
  Proof.
    apply (acyclic_sub _ (Perbyte.Rn_N Event eq_ev_dec Byte Hart Lane gmo is_write is_read is_load
                            is_store touches same_addr addr data ctrl fence hart E0 rf po LS Ctx
                            ctx_dec is_chk chk_dec lanes)).
    - intros x y H. unfold Rn_G, Perbyte.Rn_N in *.
      revert H. apply RnC_ppo_mono.
      intros m n Hmn. destruct m as [a | l]; destruct n as [c | l']; simpl in *; try contradiction.
      exact (ppow_G_sub a c Hmn).
    - exact (Perbyte.Rn_N_acyclic Event eq_ev_dec Byte Hart Value Lane gmo is_write is_read is_load
               is_store touches wval same_addr addr data ctrl fence hart E0 rf po LS Ctx ctx_dec
               is_chk chk_dec lanes Htot Hrf_touches Hrf_functional Hlanes Hkeeper_survives
               Hfault_main).
  Qed.

  (* ================================================================================================
     HEADLINE
     ================================================================================================ *)

  (* HEADLINE, position form: no totality of program order, no window premise *)
  Theorem normal_instance_pos :
    Position_before -> Position_after ->
    GenStore E_MK po_G addr data ctrl
    /\ (forall b n, ~ clos_trans (Stage2_normal_candidate.NEv Event Lane) (Cn_G_at b) n n)
    /\ (forall n, ~ clos_trans (Stage2_normal_candidate.NEv Event Lane) Rn_G n n).
  Proof.
    intros Hb Ha.
    split; [exact (generated_pos Hb Ha) |]. split; [exact G_perbyte_acyclic | exact G_mainmodel_acyclic].
  Qed.

  Theorem normal_instance :
    GenStore E_MK po_G addr data ctrl
    /\ (forall b n, ~ clos_trans (Stage2_normal_candidate.NEv Event Lane) (Cn_G_at b) n n)
    /\ (forall n, ~ clos_trans (Stage2_normal_candidate.NEv Event Lane) Rn_G n n).
  Proof.
    split; [exact generated |]. split; [exact G_perbyte_acyclic | exact G_mainmodel_acyclic].
  Qed.

End NormalInstance.
